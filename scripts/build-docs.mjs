import fs from 'node:fs';
import path from 'node:path';
const dir=new URL('../docs/',import.meta.url),out=new URL('../src/release-docs.js',import.meta.url);
const files=fs.readdirSync(dir).filter(f=>/^V[0-9][A-Za-z0-9._-]*\.md$/.test(f)).sort().reverse();
const data=files.map(name=>({name,content:fs.readFileSync(new URL(name,dir),'utf8')}));
fs.writeFileSync(out,'// Generated by npm run build:docs. Admin-only API; not under public/.\nexport const RELEASE_DOCS='+JSON.stringify(data)+';\n');
console.log('Bundled',data.length,'release notes for admin-only viewer');
